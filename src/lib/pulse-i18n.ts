const dicts: Record<Lang, Dict> = { ar, en, ku };

export function usePulseI18n() {
  const { lang } = useI18n();
  const dict = dicts[(lang as Lang) || "ar"] || ar;
  const t = (k: string) => dict[k] || k;
  return { t, lang: (lang as Lang) || "ar", dir: lang === "en" ? "ltr" : "rtl" } as const;
}
