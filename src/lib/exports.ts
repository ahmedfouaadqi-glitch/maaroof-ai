/** One-line signature: user name + privacy-safe email. */
function identityLine(payload: ExportPayload, lang: ExportLang): string {
  const id = payload.identity;
  if (!id) return "";
  const bits = [id.userName, id.userEmail].filter(Boolean);
  if (!bits.length) return "";
  return `${UI[lang].by}: ${bits.join(" · ")}`;
}


const escapeHtml = (s: any) =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function brandHeaderHtml(lang: ExportLang, payload: ExportPayload, logoData: string | null) {
  const showLogo = payload.identity?.showLogo !== false;
  const who = identityLine(payload, lang);
  return `
    <header class="brand">
      ${showLogo && logoData ? `<div class="logo" aria-hidden="true">
        <img src="${logoData}" alt="MAAROOF Ai" width="56" height="56" style="display:block;object-fit:contain;border-radius:10px;background:#fff;padding:2px"/>
      </div>` : ""}
      <div class="brand-text">
        <div class="brand-name">${BRAND}</div>
        <div class="brand-prev">${PREVIOUS_BRAND}</div>
        <div class="brand-sub">${SITE} · ${ECOSYSTEM}</div>
      </div>
      <div class="meta">${UI[lang].generated} ${escapeHtml(new Date().toLocaleString())}${who ? `<br/>${escapeHtml(who)}` : ""}</div>
    </header>
  `;
}


function sectionHtml(s: ExportSection): string {
  const h = `<h2>${escapeHtml(s.heading)}</h2>`;
  if (s.kind === "text" && s.text) {
    return `${h}<p class="prose">${escapeHtml(s.text).replace(/\n/g, "<br/>")}</p>`;
  }
  if (s.kind === "list" && s.list) {
    return `${h}<ul>${s.list.map((x) => `<li>${escapeHtml(x)}</li>`).join("")}</ul>`;
  }
  if (s.kind === "kv" && s.rows) {
    return `${h}<table class="kv"><tbody>${s.rows
      .map(([k, v]) => `<tr><th>${escapeHtml(k)}</th><td>${escapeHtml(v)}</td></tr>`)
      .join("")}</tbody></table>`;
  }
  if (s.kind === "table" && s.table) {
    const { columns, data } = s.table;
    return `${h}<table class="data"><thead><tr>${columns
      .map((c) => `<th>${escapeHtml(c)}</th>`)
      .join("")}</tr></thead><tbody>${data
      .map((row) => `<tr>${row.map((c) => `<td>${escapeHtml(c)}</td>`).join("")}</tr>`)
      .join("")}</tbody></table>`;
  }
  return h;
}

