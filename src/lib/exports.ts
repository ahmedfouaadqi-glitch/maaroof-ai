export function payloadToMarkdown(payload: ExportPayload): string {
  const lang = payload.lang || "ar";
  const cardLabels = CARD_LABELS[lang];
  const out: string[] = [`# ${payload.title}`];
  if (payload.subtitle) out.push(`_${payload.subtitle}_`);
  out.push(`> ${BRAND} · ${SITE} — ${UI[lang].generated} ${new Date().toLocaleString()}`);
  if (payload.identity?.showLogo !== false) out.push(`> Logo: ${LOGO_URL}`);
  if (identityLine(payload, lang)) out.push(`> ${identityLine(payload, lang)}`);
  out.push("");

  for (const s of payload.sections) {
    out.push(`## ${s.heading}`);
    if (s.kind === "text" && s.text) out.push(s.text, "");
    else if (s.kind === "list" && s.list) out.push(...s.list.map((x) => `- ${x}`), "");
    else if (s.kind === "kv" && s.rows) {
      out.push("| | |", "|---|---|", ...s.rows.map(([k, v]) => `| ${k} | ${v} |`), "");
    } else if (s.kind === "table" && s.table) {
      out.push(
        `| ${s.table.columns.join(" | ")} |`,
        `| ${s.table.columns.map(() => "---").join(" | ")} |`,
        ...s.table.data.map((r) => `| ${r.join(" | ")} |`),
        "",
      );
    } else if (s.kind === "cards" && s.cards) {
      for (const card of s.cards) {
        out.push("### " + card.title);
        if (card.subtitle) out.push("_" + card.subtitle + "_");
        out.push("- " + cardLabels.score + ": " + (card.score == null ? (card.status || "unmeasured") : String(card.score) + "/100"));
        if (card.fields?.length) out.push("| " + cardLabels.metric + " | " + cardLabels.value + " |", "|---|---|", ...card.fields.map(([key, value]) => "| " + key + " | " + value + " |"));
        if (card.evidence?.length) out.push("", cardLabels.evidence + ":", ...card.evidence.map((item) => "- " + item));
        if (card.notes?.length) out.push("", cardLabels.notes + ":", ...card.notes.map((item) => "- " + item));
        out.push("");
      }
    }
  }
  out.push("---", DISCLAIMER[lang]);
  return out.join("\n");
}

export function exportToMarkdown(payload: ExportPayload) {
  download(payloadToMarkdown(payload), "text/markdown;charset=utf-8", "md", payload.title);
}

/** Native Word document with an embedded logo and complete report content. */
/** Direction follows the text's first strong letter; falls back to the report language. */
export function textIsRtl(text: string, fallback: boolean): boolean {
  const m = String(text || "").match(/[\u0590-\u08FF\uFB1D-\uFEFC]|[A-Za-z\u00C0-\u024F]/);
  if (!m) return fallback;
  return /[\u0590-\u08FF\uFB1D-\uFEFC]/.test(m[0]);
}

export async function exportToWord(payload: ExportPayload) {
  const lang = payload.lang || "ar";
  const rtl = lang !== "en";
  const cardLabels = CARD_LABELS[lang];
  const {
    AlignmentType, BorderStyle, Document, Footer, Header, HeadingLevel, ImageRun,
    Packer, Paragraph, ShadingType, Table, TableCell, TableRow, TextRun, WidthType,
  } = await import("docx");
  const logoData = await optionalLogo(payload);
  const paragraph = (text: string, opts: { bold?: boolean; size?: number; color?: string; heading?: "Heading1" | "Heading2" } = {}) =>
    new Paragraph({
      ...(opts.heading ? { heading: opts.heading } : {}),
      bidirectional: textIsRtl(text, rtl),
      alignment: textIsRtl(text, rtl) ? AlignmentType.RIGHT : AlignmentType.LEFT,
      spacing: { after: 120 },
      children: [new TextRun({ text, font: "Arial", bold: opts.bold, size: opts.size, color: opts.color })],
    });
  const cellBorders = Object.fromEntries(["top", "bottom", "left", "right"].map((side) => [side, { style: BorderStyle.SINGLE, size: 1, color: "D9DEE8" }]));
  const makeTable = (columns: string[], rows: (string | number)[][]) => {
    const count = Math.max(columns.length, 1);
    const base = Math.floor(9360 / count);
    const widths = columns.map((_, index) => index === count - 1 ? 9360 - base * (count - 1) : base);
    const makeRow = (values: (string | number)[], header = false) => new TableRow({
      children: values.map((value, index) => new TableCell({
        width: { size: widths[index] || base, type: WidthType.DXA },
        borders: cellBorders,
        shading: header ? { fill: "4338CA", type: ShadingType.CLEAR } : undefined,
        margins: { top: 80, bottom: 80, left: 120, right: 120 },
        children: [new Paragraph({
          bidirectional: rtl,
          alignment: rtl ? AlignmentType.RIGHT : AlignmentType.LEFT,
          children: [new TextRun({ text: String(value ?? ""), font: "Arial", size: 19, bold: header, color: header ? "FFFFFF" : "0F172A" })],
        })],
      })),
    });
    return new Table({ width: { size: 9360, type: WidthType.DXA }, columnWidths: widths, rows: [makeRow(columns, true), ...rows.map((row) => makeRow(row))] });
  };
  const content: Array<InstanceType<typeof Paragraph> | InstanceType<typeof Table>> = [
    paragraph(payload.title, { heading: HeadingLevel.HEADING_1, bold: true, size: 36, color: "0F172A" }),
  ];
  if (payload.subtitle) content.push(paragraph(payload.subtitle, { size: 22, color: "475569" }));
  content.push(paragraph(`${UI[lang].generated}: ${new Date().toLocaleString()}`, { size: 18, color: "64748B" }));
  if (identityLine(payload, lang)) content.push(paragraph(identityLine(payload, lang), { size: 18, color: "64748B" }));
  payload.sections.forEach((section) => {
    content.push(paragraph(section.heading, { heading: HeadingLevel.HEADING_2, bold: true, size: 27, color: "4338CA" }));
    if (section.kind === "text" && section.text) section.text.split("\n").forEach((line) => content.push(paragraph(line)));
    else if (section.kind === "list" && section.list) section.list.forEach((item) => content.push(new Paragraph({ bidirectional: textIsRtl(item, rtl), alignment: textIsRtl(item, rtl) ? AlignmentType.RIGHT : AlignmentType.LEFT, bullet: { level: 0 }, children: [new TextRun({ text: item, font: "Arial", size: 22 })] })));
    else if (section.kind === "kv" && section.rows) content.push(makeTable(["", ""], section.rows.map(([key, value]) => [key, value])));
    else if (section.kind === "table" && section.table) content.push(makeTable(section.table.columns, section.table.data));
    else if (section.kind === "cards" && section.cards) {
      section.cards.forEach((card) => {
        content.push(paragraph(card.title, { bold: true, size: 24, color: "0F2454" }));
        if (card.subtitle) content.push(paragraph(card.subtitle, { size: 18, color: "64748B" }));
        content.push(paragraph(cardLabels.score + ": " + (card.score == null ? (card.status || "unmeasured") : String(card.score) + "/100") + (card.status ? " · " + card.status : ""), { bold: true, size: 18, color: "4338CA" }));
        if (card.fields?.length) content.push(makeTable([cardLabels.metric, cardLabels.value], card.fields));
        (card.evidence || []).forEach((item) => content.push(paragraph(cardLabels.evidence + ": " + item, { size: 17, color: "475569" })));
        (card.notes || []).forEach((item) => content.push(paragraph(cardLabels.note + ": " + item, { size: 17, color: "92400E" })));
      });
    }
  });
  const headerChildren = [new Paragraph({
    bidirectional: rtl,
    alignment: rtl ? AlignmentType.RIGHT : AlignmentType.LEFT,
    border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: "1E40AF", space: 8 } },
    children: [
      ...(logoData ? [new ImageRun({ type: "png", data: dataUrlBytes(logoData), transformation: { width: 52, height: 52 }, altText: { title: BRAND, description: `${BRAND} logo`, name: BRAND } }), new TextRun("  ")] : []),
      new TextRun({ text: `${BRAND}\n${SITE}`, font: "Arial", bold: true, size: 24, color: "0F2454", break: 1 }),
    ],
  })];
  const document = new Document({
    styles: { default: { document: { run: { font: "Arial", size: 22 } } } },
    sections: [{
      properties: { page: { size: { width: 12240, height: 15840 }, margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } } },
      headers: { default: new Header({ children: headerChildren }) },
      footers: { default: new Footer({ children: [paragraph(`${identityLine(payload, lang)}${identityLine(payload, lang) ? " · " : ""}${BRAND} · ${SITE}\n${DISCLAIMER[lang]}`, { size: 16, color: "64748B" })] }) },
      children: content,
    }],
  });
  const blob = await Packer.toBlob(document);
  download(blob, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "docx", payload.title);
}

/** Slide deck — one slide per section. Loaded lazily to keep the bundle light. */
export async function exportToPowerPoint(payload: ExportPayload) {
  const lang = payload.lang || "ar";
  const cardLabels = CARD_LABELS[lang];
  const { default: PptxGenJS } = await import("pptxgenjs");
  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_16x9";
  pptx.author = BRAND;
  pptx.subject = payload.title;
  const logoData = await optionalLogo(payload);
  const decorate = (slide: ReturnType<typeof pptx.addSlide>) => {
    if (logoData) slide.addImage({ data: logoData, x: 0.28, y: 0.18, w: 0.45, h: 0.45 });
    slide.addText(`${BRAND} · ${SITE}`, { x: 0.8, y: 0.2, w: 3.2, h: 0.28, fontSize: 9, bold: true, color: "0F2454" });
    slide.addText(identityLine(payload, lang), { x: 5.8, y: 5.3, w: 3.8, h: 0.22, fontSize: 7, align: "right", color: "64748B" });
  };

  const cover = pptx.addSlide();
  decorate(cover);
  cover.addText(payload.title, { x: 0.5, y: 2, w: 9, h: 1, fontSize: 30, bold: true, align: "center" });
  cover.addText(`${payload.subtitle || ""}\n${BRAND} · ${SITE}\n${identityLine(payload, lang)}`, { x: 0.5, y: 3.1, w: 9, h: 1.2, fontSize: 14, align: "center", color: "666666" });

  const ROWS_PER_SLIDE = 14;
  const CHARS_PER_SLIDE = 1200;

  for (const s of payload.sections) {
    if (s.kind === "cards" && s.cards) {
      s.cards.forEach((card) => {
        const slide = pptx.addSlide();
        decorate(slide);
        slide.addText(s.heading, { x: 0.4, y: 0.3, w: 9.2, h: 0.55, fontSize: 21, bold: true, color: "4338CA" });
        slide.addShape(pptx.ShapeType.rect, { x: 0.45, y: 1.0, w: 9.1, h: 4.0, fill: { color: "FFFFFF" }, line: { color: "D8E1EF", width: 1 } });
        slide.addText(card.title, { x: 0.7, y: 1.2, w: 7.0, h: 0.65, fontSize: 16, bold: true, color: "0F2454", breakLine: false, valign: "mid" });
        if (card.subtitle) slide.addText(card.subtitle, { x: 0.7, y: 1.82, w: 7.0, h: 0.3, fontSize: 10, color: "64748B" });
        slide.addText(card.score == null ? (card.status || "unmeasured") : cardLabels.score + ": " + String(card.score) + "/100", { x: 7.8, y: 1.2, w: 1.35, h: 0.55, fontSize: 18, bold: true, align: "center", color: card.score == null ? "64748B" : card.score >= 70 ? "166534" : card.score >= 40 ? "92400E" : "991B1B", fill: { color: card.score == null ? "F1F5F9" : card.score >= 70 ? "DCFCE7" : card.score >= 40 ? "FEF3C7" : "FEE2E2" }, margin: 0.06 });
        const details = [
          ...(card.fields || []).map(([key, value]) => String(key) + ": " + String(value)),
          ...(card.evidence || []).map((item) => cardLabels.evidence + ": " + item),
          ...(card.notes || []).map((item) => cardLabels.note + ": " + item),
        ].join("\n");
        slide.addText(details, { x: 0.7, y: 2.25, w: 8.55, h: 2.5, fontSize: 10, color: "334155", valign: "top", breakLine: false, fit: "shrink" });
      });
      continue;
    }
    if (s.kind === "table" && s.table) {
      // Split long tables across slides so no row is lost.
      const chunks: (string | number)[][][] = [];
      for (let i = 0; i < s.table.data.length; i += ROWS_PER_SLIDE) chunks.push(s.table.data.slice(i, i + ROWS_PER_SLIDE));
      if (chunks.length === 0) chunks.push([]);
      chunks.forEach((chunk, ci) => {
        const slide = pptx.addSlide();
        decorate(slide);
        slide.addText(chunks.length > 1 ? `${s.heading} (${ci + 1}/${chunks.length})` : s.heading, { x: 0.4, y: 0.3, w: 9.2, h: 0.7, fontSize: 22, bold: true });
        slide.addTable(
          [s.table!.columns.map((c) => ({ text: String(c), options: { bold: true } })), ...chunk.map((r) => r.map((c) => String(c)))] as any,
          { x: 0.4, y: 1.1, w: 9.2, fontSize: 10, border: { pt: 1, color: "CCCCCC" } },
        );
      });
      continue;
    }
    const body = s.kind === "kv" && s.rows ? s.rows.map(([k, v]) => `• ${k}: ${v}`).join("\n")
      : s.kind === "list" && s.list ? s.list.map((x) => `• ${x}`).join("\n")
      : s.text || "";
    // Split long text across slides so nothing is cut off.
    const lines = body.split("\n");
    const pages: string[] = [];
    let buf = "";
    for (const line of lines) {
      if (buf && buf.length + line.length > CHARS_PER_SLIDE) { pages.push(buf); buf = ""; }
      buf += (buf ? "\n" : "") + line;
    }
    if (buf || pages.length === 0) pages.push(buf);
    pages.forEach((page, pi) => {
      const slide = pptx.addSlide();
      decorate(slide);
      slide.addText(pages.length > 1 ? `${s.heading} (${pi + 1}/${pages.length})` : s.heading, { x: 0.4, y: 0.3, w: 9.2, h: 0.7, fontSize: 22, bold: true });
      slide.addText(page, { x: 0.4, y: 1.1, w: 9.2, h: 4, fontSize: 13, valign: "top" });
    });
  }

  const last = pptx.addSlide();
  decorate(last);
  last.addText(`${identityLine(payload, lang)}\n${BRAND} · ${SITE}\n\n${DISCLAIMER[lang]}`, { x: 0.5, y: 2, w: 9, h: 2.4, fontSize: 10, color: "666666", align: "center" });


  await pptx.writeFile({ fileName: `${payload.title.replace(/[\\/?*[\]:]/g, "_")}-${new Date().toISOString().slice(0, 10)}.pptx` });
}
